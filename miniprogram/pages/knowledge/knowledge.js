const app = getApp();

function p(text) {
  return { name: 'p', attrs: { class: 'article-p' }, children: [{ type: 'text', text }] };
}

function h3(text) {
  return { name: 'h3', attrs: { class: 'article-h3' }, children: [{ type: 'text', text }] };
}

function ul(items) {
  return {
    name: 'ul',
    attrs: { class: 'article-ul' },
    children: items.map(text => ({
      name: 'li',
      attrs: { class: 'article-li' },
      children: [{ type: 'text', text }]
    }))
  };
}

