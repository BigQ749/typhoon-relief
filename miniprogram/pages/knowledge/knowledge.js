const tabs = [
  { key: 'before', label: '台风前' },
  { key: 'during', label: '台风中' },
  { key: 'after', label: '台风后' },
  { key: 'special', label: '人群/清单' }
];

function buildList(category) {
  const list = ARTICLES[category] || [];
  return {
    heroArticle: list[0] || null,
    secondaryArticles: list.slice(1)
  };
}

Page({
  data: {
    currentTab: 0,
    tabs,
    heroArticle: ARTICLES.before[0],
    secondaryArticles: ARTICLES.before.slice(1),
    quickTips: [
      '非必要不外出',
      '远离玻璃门窗',
      '低洼区域提前转移',
      '求救时说明位置、人数、伤情'
    ]
  },

  switchTab(e) {
    const index = Number(e.currentTarget.dataset.index);
    const category = e.currentTarget.dataset.category;
    this.setData({
      currentTab: index,
      ...buildList(category)
    });
  },

  goToDetail(e) {
    const id = e.currentTarget.dataset.id;
    let article = null;

    Object.keys(ARTICLES).some(category => {
      article = ARTICLES[category].find(item => item.id === id);
      return Boolean(article);
    });

    if (article) {
      app.globalData.currentArticle = {
        ...article,
        viewCount: undefined
      };
      wx.navigateTo({ url: '/pages/knowledge-detail/knowledge-detail' });
    }
  }
});
